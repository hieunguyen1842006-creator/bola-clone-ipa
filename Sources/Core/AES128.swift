    static let rcon: [UInt8] = [
        0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1B,0x36,
    ]

    // MARK: - mở rộng khoá (11 round key × 16 byte)

    public static func expandKey(_ key: [UInt8]) -> [UInt8] {
        precondition(key.count == 16, "AES-128 cần khoá 16 byte")
        var w = [UInt8](repeating: 0, count: 176)
        for i in 0..<16 { w[i] = key[i] }
        var round = 1
        var off = 16
        while off < 176 {
            var t = Array(w[(off - 4)..<off])
            if off % 16 == 0 {
                t = [t[1], t[2], t[3], t[0]]                 // RotWord
                for i in 0..<4 { t[i] = sbox[Int(t[i])] }    // SubWord
                t[0] ^= rcon[round]
                round += 1
            }
            for i in 0..<4 {
                w[off] = w[off - 16] ^ t[i]
                off += 1
            }
        }
        return w
    }

    // MARK: - biến đổi trạng thái

    @inline(__always)
    static func xtime(_ a: UInt8) -> UInt8 {
        ((a << 1) ^ ((a & 0x80) != 0 ? 0x1B : 0x00))
    }

    @inline(__always)
    static func mul(_ a: UInt8, _ b: UInt8) -> UInt8 {
        var result: UInt8 = 0
        var x = a
        var y = b
        while y != 0 {
            if (y & 1) != 0 { result ^= x }
            x = xtime(x)
            y >>= 1
        }
        return result
    }

    /// Mã hoá 1 block 16 byte tại chỗ.
    public static func encryptBlock(_ block: inout [UInt8], roundKeys w: [UInt8]) {
        precondition(block.count == 16)
        addRoundKey(&block, w, 0)
        for round in 1..<10 {
            subBytes(&block)
            shiftRows(&block)
            mixColumns(&block)
            addRoundKey(&block, w, round)
        }
        subBytes(&block)
        shiftRows(&block)
        addRoundKey(&block, w, 10)
    }

    /// Giải mã 1 block 16 byte tại chỗ.
    public static func decryptBlock(_ block: inout [UInt8], roundKeys w: [UInt8]) {
        precondition(block.count == 16)
        addRoundKey(&block, w, 10)
        for round in stride(from: 9, through: 1, by: -1) {
            invShiftRows(&block)
            invSubBytes(&block)
            addRoundKey(&block, w, round)
            invMixColumns(&block)
        }
        invShiftRows(&block)
        invSubBytes(&block)
        addRoundKey(&block, w, 0)
    }

    @inline(__always)
    static func addRoundKey(_ s: inout [UInt8], _ w: [UInt8], _ round: Int) {
        let base = round * 16
        for i in 0..<16 { s[i] ^= w[base + i] }
    }

    @inline(__always)
    static func subBytes(_ s: inout [UInt8]) {
        for i in 0..<16 { s[i] = sbox[Int(s[i])] }
    }

    @inline(__always)
    static func invSubBytes(_ s: inout [UInt8]) {
        for i in 0..<16 { s[i] = invSbox[Int(s[i])] }
    }

    /// Trạng thái xếp theo cột: s[col*4 + row].
    @inline(__always)
    static func shiftRows(_ s: inout [UInt8]) {
        var t = s
        for row in 1..<4 {
            for col in 0..<4 {
                t[col * 4 + row] = s[((col + row) % 4) * 4 + row]
            }
        }
        s = t
    }

    @inline(__always)
    static func invShiftRows(_ s: inout [UInt8]) {
        var t = s
        for row in 1..<4 {
            for col in 0..<4 {
                t[((col + row) % 4) * 4 + row] = s[col * 4 + row]
            }
        }
        s = t
    }

    @inline(__always)
    static func mixColumns(_ s: inout [UInt8]) {
        for c in 0..<4 {
            let i = c * 4
            let a0 = s[i], a1 = s[i + 1], a2 = s[i + 2], a3 = s[i + 3]
            s[i]     = mul(a0, 2) ^ mul(a1, 3) ^ a2 ^ a3
            s[i + 1] = a0 ^ mul(a1, 2) ^ mul(a2, 3) ^ a3
            s[i + 2] = a0 ^ a1 ^ mul(a2, 2) ^ mul(a3, 3)
            s[i + 3] = mul(a0, 3) ^ a1 ^ a2 ^ mul(a3, 2)
        }
    }

    @inline(__always)
    static func invMixColumns(_ s: inout [UInt8]) {
        for c in 0..<4 {
            let i = c * 4
            let a0 = s[i], a1 = s[i + 1], a2 = s[i + 2], a3 = s[i + 3]
            s[i]     = mul(a0, 14) ^ mul(a1, 11) ^ mul(a2, 13) ^ mul(a3, 9)
            s[i + 1] = mul(a0, 9)  ^ mul(a1, 14) ^ mul(a2, 11) ^ mul(a3, 13)
            s[i + 2] = mul(a0, 13) ^ mul(a1, 9)  ^ mul(a2, 14) ^ mul(a3, 11)
            s[i + 3] = mul(a0, 11) ^ mul(a1, 13) ^ mul(a2, 9)  ^ mul(a3, 14)
        }
    }

    // MARK: - CBC (không pad — caller tự pad/cắt)

    /// AES-128-CBC trên dữ liệu đã bội 16. Trả nil nếu độ dài sai.
    public static func cbcEncrypt(key: [UInt8], iv: [UInt8], data: [UInt8]) -> [UInt8]? {
        guard key.count == 16, iv.count == 16, data.count % 16 == 0 else { return nil }
        let w = expandKey(key)
        var prev = iv
        var out = [UInt8](repeating: 0, count: data.count)
        var off = 0
        while off < data.count {
            var block = Array(data[off..<(off + 16)])
            for i in 0..<16 { block[i] ^= prev[i] }
            encryptBlock(&block, roundKeys: w)
            for i in 0..<16 { out[off + i] = block[i] }
            prev = block
            off += 16
        }
        return out
    }

    /// AES-128-CBC giải mã. Trả nil nếu độ dài sai.
    public static func cbcDecrypt(key: [UInt8], iv: [UInt8], data: [UInt8]) -> [UInt8]? {
        guard key.count == 16, iv.count == 16, data.count % 16 == 0 else { return nil }
        let w = expandKey(key)
        var prev = iv
        var out = [UInt8](repeating: 0, count: data.count)
        var off = 0
        while off < data.count {
            let cipherBlock = Array(data[off..<(off + 16)])
            var block = cipherBlock
            decryptBlock(&block, roundKeys: w)
            for i in 0..<16 { out[off + i] = block[i] ^ prev[i] }
            prev = cipherBlock
            off += 16
        }
        return out
    }
